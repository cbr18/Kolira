"""Translatable texts that live in data, not in code literals.

    python3 tools/gen_i18n_strings.py          # write src/core/i18n_strings.py
    python3 tools/gen_i18n_strings.py --fill   # put tools/i18n_ru.py into i18n/py_ru.ts

Run by scripts/update-translations.sh (before pylupdate6 and after it).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

OUT = ROOT / "src/core/i18n_strings.py"
TS = ROOT / "i18n/py_ru.ts"


def field_texts() -> list[str]:
    data = json.loads((ROOT / "src/core/theme_fields.json").read_text(encoding="utf-8"))
    out: list[str] = []
    for f in data["fields"]:
        for key in ("label", "description"):
            text = f.get(key) or ""
            if text and text not in out:
                out.append(text)
    return out


def app_texts() -> list[str]:
    from core.tracked_apps import TRACKED_APPS  # noqa: E402

    return list(dict.fromkeys(a.description for a in TRACKED_APPS if a.description))


def core_texts() -> list[str]:
    import i18n_ru  # noqa: E402

    return list(i18n_ru.CORE)


def message_texts() -> list[str]:
    import i18n_ru  # noqa: E402

    return list(i18n_ru.CORE_MESSAGES)


def write() -> None:
    lines = [
        '"""Generated by tools/gen_i18n_strings.py — do not edit.',
        "",
        "Texts that reach the UI from data (theme_fields.json, the tracked-app",
        "registry, the Rust core) listed for pylupdate6. Contexts: ThemeFields,",
        'TrackedApps, Core."""',
        "",
        "from PySide6.QtCore import QT_TRANSLATE_NOOP",
        "",
        "STRINGS = [",
    ]
    for context, texts in (("ThemeFields", field_texts()), ("TrackedApps", app_texts()), ("Core", core_texts()),
                            ("CoreMessages", message_texts())):
        for text in texts:
            lines.append(f"    QT_TRANSLATE_NOOP({context!r}, {text!r}),")
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _xml(text: str) -> str:
    # As pylupdate6 writes it: & < > escaped, quotes and apostrophes kept.
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def fill() -> int:
    import i18n_ru  # noqa: E402

    tables = {
        "ThemeFields": i18n_ru.THEME_FIELDS,
        "TrackedApps": i18n_ru.TRACKED_APPS,
        "Core": i18n_ru.CORE,
        "CoreMessages": i18n_ru.CORE_MESSAGES,
        "AppThemeCore": i18n_ru.APP_THEME_CORE,
    }
    ts = TS.read_text(encoding="utf-8")
    filled = 0

    def ctx_block(match: re.Match) -> str:
        nonlocal filled
        name, body = match.group(1), match.group(2)
        table = tables.get(name)
        if not table:
            return match.group(0)
        for src, dst in table.items():
            pattern = re.compile(
                r"(<source>" + re.escape(_xml(src)) + r"</source>\s*)(?:<translation(?: type=\"unfinished\")?>[^<]*</translation>|<translation(?: type=\"unfinished\")? */>)"
            )
            body, n = pattern.subn(lambda m: m.group(1) + "<translation>" + _xml(dst) + "</translation>", body)
            filled += n
        return f"<context>\n    <name>{name}</name>{body}</context>"

    ts = re.sub(r"<context>\s*<name>([^<]+)</name>(.*?)</context>", ctx_block, ts, flags=re.S)
    TS.write_text(ts, encoding="utf-8")
    return filled


if __name__ == "__main__":
    if "--fill" in sys.argv:
        print(f"filled {fill()} translations")
    else:
        write()
        print(f"wrote {OUT.relative_to(ROOT)}")
