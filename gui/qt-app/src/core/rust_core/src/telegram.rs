//! Telegram Desktop colours from the palette.
//!
//! Telegram's look is a palette of ~590 named colours (`colors.palette` in
//! desktop-app/lib_ui, GPL-3). A theme can be a plain `.tdesktop-palette`
//! file (`key: #rrggbb;` or `key: otherKey;` lines) — no archive, no chat
//! background, so the user's chat wallpaper stays.
//!
//! The default palette is fetched from the official repository (cached; the
//! kit does not ship Telegram's GPL file) and recoloured the way Kvantum
//! themes are (`kvantum::Recolor`, OKLab): neutrals move along the palette's
//! background → text scale, Telegram blue becomes the accent, the green of
//! outgoing messages becomes an accent tint (a second recolour anchored on
//! that green). References between keys are kept, and `windowFgActive` (text
//! on blue: buttons, the open chat, userpics) gets the palette's on-accent
//! text — a light base recoloured dark would otherwise turn it dark on blue.
//!
//! Telegram keeps the applied theme inside its own encrypted settings, so a
//! theme cannot be switched from outside: the file is opened in Telegram,
//! which shows a preview with an *Apply* button.

use std::path::PathBuf;

use anyhow::{anyhow, Context, Result};

use crate::kvantum::Recolor;
use crate::palette::{kde_roles, Palette, Rgb};

/// Where the generated palette lives (and travels in a theme).
pub const PALETTE_FILE: &str = ".local/share/TelegramDesktop/theme-profile.tdesktop-palette";
const DEFAULT_PALETTE_URL: &str = "https://raw.githubusercontent.com/desktop-app/lib_ui/master/ui/colors.palette";

/// Default Telegram palette anchors: background, text, accent blue, and the
/// green of outgoing messages.
const BASE_BG: Rgb = Rgb(0xff, 0xff, 0xff);
const BASE_FG: Rgb = Rgb(0, 0, 0);
const BASE_BLUE: Rgb = Rgb(0x40, 0xa7, 0xe3);
const BASE_OUT_GREEN: Rgb = Rgb(0x57, 0xb8, 0x4c);

fn cache_file() -> PathBuf {
    crate::paths::cache_home().join("theme-profile/telegram-colors.palette")
}

/// Telegram's default palette: the cached copy, else downloaded.
pub fn default_palette() -> Result<String> {
    let cache = cache_file();
    if let Ok(text) = std::fs::read_to_string(&cache) {
        if !text.trim().is_empty() {
            return Ok(text);
        }
    }
    let text = crate::net::http_get(DEFAULT_PALETTE_URL, 1 << 20).context("cannot fetch Telegram's default palette")?;
    if parse(&text).len() < 100 {
        return Err(anyhow!("unexpected Telegram palette format"));
    }
    if let Some(dir) = cache.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&cache, &text)?;
    Ok(text)
}

/// `key: value;` entries of a palette file, in order (comments dropped).
fn parse(text: &str) -> Vec<(String, String)> {
    text.lines()
        .filter_map(|line| {
            let line = line.split("//").next()?.trim();
            let (key, rest) = line.split_once(':')?;
            let key = key.trim();
            let value = rest.trim().strip_suffix(';')?.trim();
            (!key.is_empty() && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') && !value.is_empty())
                .then(|| (key.to_string(), value.to_string()))
        })
        .collect()
}

/// Outgoing-message colours (green in the default palette).
fn outgoing(key: &str) -> bool {
    key.starts_with("msgOut") || key.starts_with("historyOut") || key.starts_with("msgFileOut") || key.starts_with("msgFileThumbLinkOut")
}

/// The recoloured palette file for palette `p`.
pub fn generate(p: &Palette, default_palette: &str) -> String {
    let roles = kde_roles(p);
    let main = Recolor::new(BASE_BG, BASE_FG, BASE_BLUE, p);
    let out = Recolor::new(BASE_BG, BASE_FG, BASE_OUT_GREEN, p);
    let mut text = format!("// {} — generated by theme-profile from Telegram's default palette (GPL-3, desktop-app/lib_ui)\n", p.name);
    for (key, value) in parse(default_palette) {
        let value = if key == "windowFgActive" {
            roles.selection_text.hex()
        } else if value.starts_with('#') {
            let recolor = if outgoing(&key) { &out } else { &main };
            recolor.map_text(&value)
        } else {
            value
        };
        text.push_str(&format!("{key}: {value};\n"));
    }
    text
}

fn no_apply() -> bool {
    std::env::var("KTM_THEME_NO_APPLY").as_deref() == Ok("1")
}

/// Telegram's binary, if installed.
fn telegram_bin() -> Option<PathBuf> {
    ["Telegram", "telegram-desktop"].iter().find_map(|b| which::which(b).ok())
}

/// Open the palette in Telegram: a running Telegram shows a preview with
/// *Apply*. Returns whether Telegram was asked.
pub fn open_in_telegram(file: &std::path::Path) -> bool {
    if no_apply() || !file.is_file() {
        return false;
    }
    let Some(bin) = telegram_bin() else { return false };
    std::process::Command::new(bin)
        .arg("--")
        .arg(file)
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .spawn()
        .is_ok()
}

/// Palette target outcome.
pub enum Outcome {
    /// Written; whether Telegram was asked to show the preview.
    Written(PathBuf, bool),
    /// Skipped, with the reason (not installed, default palette unavailable).
    Skipped(String),
}

/// Palette target: write the file and open it in Telegram. Never fails the
/// whole palette apply: without Telegram or its default palette (offline) it
/// is skipped.
pub fn apply_palette(p: &Palette) -> Result<Outcome> {
    if telegram_bin().is_none() {
        return Ok(Outcome::Skipped("Telegram is not installed".into()));
    }
    let base = match default_palette() {
        Ok(text) => text,
        Err(e) => return Ok(Outcome::Skipped(format!("{e:#}"))),
    };
    let text = generate(p, &base);
    let path = crate::paths::home_dir().join(PALETTE_FILE);
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&path, text)?;
    let opened = open_in_telegram(&path);
    Ok(Outcome::Written(path, opened))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "// header\nwindowBg: #ffffff; // window background\nwindowFg: #000000;\nwindowBgActive: #40a7e3;\nwindowFgActive: #ffffff; // text on active\nactiveButtonFg: windowFgActive;\nmsgOutBg: #effdde;\nshadowFg: #00000018;\nbadline\n";

    #[test]
    fn parses_keys_values_and_references() {
        let entries = parse(SAMPLE);
        assert_eq!(entries.len(), 7);
        assert_eq!(entries[4], ("activeButtonFg".to_string(), "windowFgActive".to_string()));
    }

    #[test]
    fn recolours_into_the_palette() {
        let p = crate::palette::parse_base16(include_str!("../data/base16/everforest.yaml"), "t").unwrap();
        let roles = kde_roles(&p);
        let out = generate(&p, SAMPLE);
        let get = |k: &str| out.lines().find_map(|l| l.strip_prefix(&format!("{k}: "))).unwrap().trim_end_matches(';').to_string();
        assert_eq!(get("activeButtonFg"), "windowFgActive", "references kept");
        assert_eq!(get("windowFgActive"), roles.selection_text.hex(), "text on the accent");
        assert_ne!(get("windowBg"), "#ffffff", "white background follows the dark palette");
        assert!(get("shadowFg").len() == 9 && get("shadowFg").ends_with("18"), "alpha kept: {}", get("shadowFg"));
        assert_ne!(get("msgOutBg"), "#effdde", "outgoing green recoloured");
    }
}
