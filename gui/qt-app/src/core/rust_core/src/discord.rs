//! Discord through its theming clients (stock Discord has no themes):
//! Vencord (`~/.config/Vencord`) and Vesktop (`~/.config/vesktop`).
//!
//! * a theme carries the client's `themes/` folder and, from
//!   `settings/settings.json`, only `enabledThemes` / `themeLinks`;
//! * the palette generates `themes/theme-profile.theme.css` on top of the
//!   popular midnight theme (MIT, refact0r — the approach of matugen's
//!   template; midnight is loaded from its site) and enables it. Vencord
//!   reloads themes by itself.

use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use anyhow::Result;

use crate::palette::{kde_roles, Palette, Rgb};

pub const THEME_FILE: &str = "theme-profile.theme.css";
/// (client name, config folder relative to `$HOME`).
pub const CLIENTS: &[(&str, &str)] = &[("Vencord", ".config/Vencord"), ("Vesktop", ".config/vesktop")];
pub const SETTINGS_KEYS: &[&str] = &["enabledThemes", "themeLinks"];

fn client_dir(rel: &str) -> PathBuf {
    crate::paths::home_dir().join(rel)
}

/// Tracked files of every client set up here.
pub fn config_paths() -> Vec<String> {
    CLIENTS
        .iter()
        .filter(|(_, rel)| client_dir(rel).exists())
        .flat_map(|(_, rel)| [format!("{rel}/settings/settings.json"), format!("{rel}/themes")])
        .collect()
}

/// Is `rel` a client settings file (merged: only the theme keys)?
pub fn is_settings(rel: &str) -> bool {
    CLIENTS.iter().any(|(_, base)| rel == format!("{base}/settings/settings.json"))
}

fn hex(c: Rgb) -> String {
    c.hex()
}

/// The palette as a midnight-discord theme.
pub fn css(p: &Palette) -> String {
    let r = kde_roles(p);
    let mut out = String::new();
    let _ = writeln!(
        out,
        "/**\n * @name Theme Profile ({})\n * @description Colours generated by theme-profile on top of midnight (MIT, refact0r).\n * @author theme-profile\n * @version 1.0.0\n * @source https://github.com/refact0r/midnight-discord\n*/\n",
        p.name.replace("*/", "")
    );
    out.push_str("@import url('https://refact0r.github.io/midnight-discord/build/midnight.css');\n\n:root {\n");
    let mut var = |name: &str, c: Rgb| {
        let _ = writeln!(out, "\t--{name}: {};", hex(c));
    };
    var("online-indicator", r.positive);
    var("dnd-indicator", r.negative);
    var("idle-indicator", r.neutral);
    var("streaming-indicator", r.accent);
    var("accent-1", r.link);
    var("accent-2", r.accent);
    var("accent-3", r.accent);
    var("accent-4", r.accent.mix(r.text, 0.15));
    var("accent-5", r.accent.mix(r.window, 0.2));
    var("accent-new", r.accent);
    var("mention", r.window_alt);
    var("mention-hover", r.hover.mix(r.window, 0.7));
    var("text-0", r.selection_text);
    var("text-1", r.text);
    var("text-2", r.text);
    var("text-3", r.text.mix(r.window, 0.1));
    var("text-4", r.text_inactive);
    var("text-5", r.text_inactive.mix(r.window, 0.3));
    var("bg-1", r.button_alt);
    var("bg-2", r.button);
    var("bg-3", r.window_alt);
    var("bg-4", r.window);
    var("hover", r.view_alt);
    var("active", r.view_alt.mix(r.accent, 0.15));
    var("message-hover", r.window_alt);
    out.push_str("}\n");
    out
}

/// `settings.json` with `theme` added to `enabledThemes` (positional patch).
pub fn enable(settings: &str, theme: &str) -> String {
    let current: Vec<String> = serde_json::from_str::<serde_json::Value>(settings)
        .ok()
        .and_then(|v| v.get("enabledThemes").cloned())
        .and_then(|v| serde_json::from_value(v).ok())
        .unwrap_or_default();
    let mut themes = current;
    if !themes.iter().any(|t| t == theme) {
        themes.push(theme.to_string());
    }
    let snippet = format!("{{\"enabledThemes\": {}}}", serde_json::to_string(&themes).unwrap_or_else(|_| "[]".into()));
    let base = if settings.trim().is_empty() { "{}" } else { settings };
    crate::appearance::jsonc_merge(&snippet, base, &["enabledThemes"])
}

/// Palette target `discord`: write and enable the generated theme in every
/// client set up here. Returns the theme files written.
pub fn apply_palette(p: &Palette) -> Result<Vec<PathBuf>> {
    let mut written = Vec::new();
    for (_, rel) in CLIENTS {
        let dir = client_dir(rel);
        if !dir.exists() {
            continue;
        }
        fs::create_dir_all(dir.join("themes"))?;
        let file = dir.join("themes").join(THEME_FILE);
        fs::write(&file, css(p))?;
        let settings = dir.join("settings/settings.json");
        let text = fs::read_to_string(&settings).unwrap_or_default();
        fs::create_dir_all(dir.join("settings"))?;
        fs::write(&settings, enable(&text, THEME_FILE))?;
        written.push(file);
    }
    Ok(written)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn enable_adds_once_and_keeps_other_settings() {
        let s = "{\n  \"autoUpdate\": true,\n  \"enabledThemes\": [\"mine.css\"]\n}\n";
        let once = enable(s, THEME_FILE);
        let v: serde_json::Value = serde_json::from_str(&once).unwrap();
        assert_eq!(v["enabledThemes"], serde_json::json!(["mine.css", THEME_FILE]));
        assert_eq!(v["autoUpdate"], true);
        assert_eq!(enable(&once, THEME_FILE), once);
        let fresh: serde_json::Value = serde_json::from_str(&enable("", THEME_FILE)).unwrap();
        assert_eq!(fresh["enabledThemes"], serde_json::json!([THEME_FILE]));
    }
}
