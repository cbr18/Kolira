//! Steam client colours through Adwaita for Steam.
//!
//! Steam has no theme support of its own. Adwaita for Steam
//! (github.com/tkashkin/Adwaita-for-Steam, GPL-3) patches the client's
//! `steamui` files; its installer takes `--custom-css FILE`, loaded after the
//! skin, so the palette becomes a set of the skin's `--adw-*` variables and
//! nothing in the skin itself changes. `--color-scheme` follows the palette
//! variant and `--accent-color` the accent.
//!
//! The skin is downloaded from its official repository on demand (cached in
//! `~/.cache/theme-profile/adwaita-for-steam`) and installed with
//! `python3 install.py`. Steam picks it up after a restart, and a Steam update
//! overwrites the patch: applying a theme that carries the colours re-installs
//! when the colours changed or the patch is gone. Remove it with
//! `python3 ~/.cache/theme-profile/adwaita-for-steam/install.py --uninstall`.
//!
//! Opt-in palette target (`--targets=steam`): it modifies another program's
//! files.

use std::fmt::Write as _;
use std::fs;
use std::io::Read;
use std::path::{Path, PathBuf};

use anyhow::{anyhow, Context, Result};
use sha2::{Digest, Sha256};

use crate::palette::{kde_roles, Palette, Rgb, Variant};

/// The colours (and the variant/accent the installer needs) as a theme file.
pub const CSS_FILE: &str = ".config/theme-profile/steam.css";
const SKIN_ZIP: &str = "https://codeload.github.com/tkashkin/Adwaita-for-Steam/zip/refs/heads/master";

fn cache_dir() -> PathBuf {
    crate::paths::cache_home().join("theme-profile")
}

fn skin_dir() -> PathBuf {
    cache_dir().join("adwaita-for-steam")
}

fn stamp_file() -> PathBuf {
    cache_dir().join("steam-installed.sha256")
}

fn hex_a(c: Rgb, alpha: f64) -> String {
    format!("rgba({}, {}, {}, {:.2})", c.0, c.1, c.2, alpha)
}

/// `--adw-*` variables for palette `p` (the shape of the skin's colour themes).
/// The first line records the variant for the installer's `--color-scheme`.
pub fn css(p: &Palette) -> String {
    let r = kde_roles(p);
    let dark = p.variant == Variant::Dark;
    let shade = if dark { "rgba(0, 0, 0, 0.36)" } else { "rgba(0, 0, 0, 0.07)" };
    let card = if dark { hex_a(Rgb(255, 255, 255), 0.08) } else { hex_a(Rgb(255, 255, 255), 0.8) };
    let on = |c: Rgb| if c.luminance() > 0.45 { "rgba(0, 0, 0, 0.8)".to_string() } else { "#ffffff".to_string() };
    let rows: Vec<(&str, String)> = vec![
        ("color-scheme", if dark { "dark" } else { "light" }.to_string()),
        ("accent-bg-light", r.accent.hex()),
        ("accent-bg-dark", r.accent.hex()),
        ("destructive-bg-light", r.negative.hex()),
        ("destructive-bg-dark", r.negative.hex()),
        ("destructive-fg", on(r.negative)),
        ("success-bg-light", r.positive.hex()),
        ("success-bg-dark", r.positive.hex()),
        ("success-fg", on(r.positive)),
        ("warning-bg-light", r.neutral.hex()),
        ("warning-bg-dark", r.neutral.hex()),
        ("warning-fg", on(r.neutral)),
        ("error-bg-light", r.negative.hex()),
        ("error-bg-dark", r.negative.hex()),
        ("error-fg", on(r.negative)),
        ("window-bg", r.window.hex()),
        ("window-fg", r.text.hex()),
        ("view-bg", r.view.hex()),
        ("view-fg", r.text.hex()),
        ("headerbar-bg", r.header.hex()),
        ("headerbar-fg", r.text.hex()),
        ("headerbar-backdrop", r.window.hex()),
        ("headerbar-shade", shade.to_string()),
        ("headerbar-darker-shade", shade.to_string()),
        ("sidebar-bg", r.window_alt.hex()),
        ("sidebar-fg", r.text.hex()),
        ("sidebar-backdrop", r.window.hex()),
        ("sidebar-shade", shade.to_string()),
        ("secondary-sidebar-bg", r.window_alt.hex()),
        ("secondary-sidebar-fg", r.text.hex()),
        ("secondary-sidebar-backdrop", r.window.hex()),
        ("secondary-sidebar-shade", shade.to_string()),
        ("card-bg", card),
        ("card-fg", r.text.hex()),
        ("card-shade", shade.to_string()),
        ("dialog-bg", r.window_alt.hex()),
        ("dialog-fg", r.text.hex()),
        ("popover-bg", r.window_alt.hex()),
        ("popover-fg", r.text.hex()),
        ("popover-shade", shade.to_string()),
        ("thumbnail-bg", r.window_alt.hex()),
        ("thumbnail-fg", r.text.hex()),
        ("shade", shade.to_string()),
    ];
    let mut out = format!("/* {} — generated by theme-profile for Adwaita for Steam ({}) */\n:root\n{{\n", p.name, if dark { "dark" } else { "light" });
    for (name, value) in rows {
        let _ = writeln!(out, "\t--adw-{name}: {value} !important;");
    }
    out.push_str("}\n");
    out
}

/// Variant and accent recorded in a generated file (for the installer).
fn scheme_and_accent(css: &str) -> (String, Option<String>) {
    let scheme = if css.lines().next().is_some_and(|l| l.contains("(light)")) { "light" } else { "dark" };
    let accent = css.lines().find_map(|l| l.trim().strip_prefix("--adw-accent-bg-light:")).map(|v| v.trim().trim_end_matches(';').trim_end_matches("!important").trim().to_string());
    (scheme.to_string(), accent)
}

/// A Steam installation the skin can patch.
pub fn steam_installed() -> bool {
    let home = crate::paths::home_dir();
    which::which("steam").is_ok() || home.join(".local/share/Steam/steamui").is_dir() || home.join(".steam/steam/steamui").is_dir()
}

fn no_apply() -> bool {
    std::env::var("KTM_THEME_NO_APPLY").as_deref() == Ok("1")
}

/// The skin's installer, downloaded once from the official repository.
fn ensure_skin() -> Result<PathBuf> {
    let dir = skin_dir();
    if dir.join("install.py").is_file() {
        return Ok(dir);
    }
    let bytes = crate::net::http_get_bytes(SKIN_ZIP, 64 << 20).context("cannot download Adwaita for Steam")?;
    let staging = dir.with_extension("tmp-theme-profile");
    if staging.exists() {
        fs::remove_dir_all(&staging)?;
    }
    fs::create_dir_all(&staging)?;
    let mut archive = zip::ZipArchive::new(std::io::Cursor::new(bytes)).context("bad Adwaita for Steam archive")?;
    for i in 0..archive.len() {
        let mut entry = archive.by_index(i)?;
        let Some(rel) = entry.enclosed_name() else { continue };
        // Drop the archive's top folder (Adwaita-for-Steam-master/).
        let rel: PathBuf = rel.components().skip(1).collect();
        if rel.as_os_str().is_empty() {
            continue;
        }
        let out = staging.join(&rel);
        if entry.is_dir() {
            fs::create_dir_all(&out)?;
            continue;
        }
        if entry.is_symlink() {
            continue;
        }
        if let Some(parent) = out.parent() {
            fs::create_dir_all(parent)?;
        }
        let mut data = Vec::new();
        entry.read_to_end(&mut data)?;
        fs::write(&out, data)?;
    }
    if !staging.join("install.py").is_file() {
        let _ = fs::remove_dir_all(&staging);
        return Err(anyhow!("Adwaita for Steam archive has no install.py"));
    }
    if dir.exists() {
        fs::remove_dir_all(&dir)?;
    }
    fs::rename(&staging, &dir)?;
    Ok(dir)
}

fn digest(text: &str) -> String {
    format!("{:x}", Sha256::digest(text.as_bytes()))
}

/// Is the skin still in Steam's files (a Steam update removes it)?
fn skin_present() -> bool {
    let home = crate::paths::home_dir();
    [home.join(".local/share/Steam/steamui"), home.join(".steam/steam/steamui")]
        .iter()
        .any(|d| d.join("adwaita").exists() || d.join("libraryroot.custom.css").is_file())
}

/// Install the skin with the colours in `css_file`. `force` re-installs even
/// when the same colours are already in place.
pub fn install(css_file: &Path, force: bool) -> Result<String> {
    let css = fs::read_to_string(css_file).with_context(|| format!("cannot read {}", css_file.display()))?;
    let sum = digest(&css);
    if !force && fs::read_to_string(stamp_file()).ok().as_deref() == Some(sum.as_str()) && skin_present() {
        return Ok("already installed with these colours".into());
    }
    if no_apply() {
        return Ok("not installed (KTM_THEME_NO_APPLY)".into());
    }
    let skin = ensure_skin()?;
    let (scheme, accent) = scheme_and_accent(&css);
    let mut cmd = std::process::Command::new("python3");
    cmd.current_dir(&skin)
        .arg("install.py")
        .args(["--color-scheme", &scheme, "--font", "system", "--custom-css"])
        .arg(css_file);
    if let Some(accent) = accent.filter(|a| a.starts_with('#')) {
        cmd.args(["--accent-color", &accent]);
    }
    let out = cmd.output().context("cannot run python3 install.py")?;
    if !out.status.success() {
        let err = String::from_utf8_lossy(&out.stderr);
        return Err(anyhow!("Adwaita for Steam installer failed: {}", err.lines().last().unwrap_or("").trim()));
    }
    fs::write(stamp_file(), sum)?;
    Ok("installed — restart Steam to see it".into())
}

/// Palette target: write the colours and install the skin.
pub fn apply_palette(p: &Palette) -> Result<Option<(PathBuf, String)>> {
    if !steam_installed() {
        return Ok(None);
    }
    let path = crate::paths::home_dir().join(CSS_FILE);
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    fs::write(&path, css(p))?;
    let note = install(&path, false)?;
    Ok(Some((path, note)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn css_follows_the_palette() {
        let p = crate::palette::parse_base16(include_str!("../data/base16/everforest.yaml"), "t").unwrap();
        let roles = kde_roles(&p);
        let out = css(&p);
        assert!(out.starts_with("/* ") && out.lines().next().unwrap().contains("(dark)"));
        assert!(out.contains(&format!("--adw-window-bg: {} !important;", roles.window.hex())));
        assert!(out.contains(&format!("--adw-accent-bg-light: {} !important;", roles.accent.hex())));
        let (scheme, accent) = scheme_and_accent(&out);
        assert_eq!(scheme, "dark");
        assert_eq!(accent, Some(roles.accent.hex()));
    }
}
